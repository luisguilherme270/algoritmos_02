#include <stdio.h>
#include "biblioteca.h"

float 
Calcular_soma(float numero_1, float numero_2)
  {
  float resultado = numero_1 + numero_2;
  return resultado;
  }
float
Calcular_subtracao(float numero_01, float numero_02)
  {
  float resultado = numero_01 - numero_02;
  return resultado;
  }
float
Calcular_multiplicacao(float numero_01, float numero_02)
  {
  float resultado = numero_01 * numero_02;
  return resultado;
  }
float
Calcular_divisao(float numero_01, float numero_02)
  {
  float resultado = numero_01 / numero_02;
  return resultado;
  }